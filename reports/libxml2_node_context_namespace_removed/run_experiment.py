"""Run the archived character reducer, namespace-free rerun, and paired screens.

Execute with Python in WSL, after work/prepare_node_context.py builds the probes.
Every invocation creates a fresh directory under runs/.
"""
from collections import Counter
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo
import csv
import hashlib
import json
import os
import subprocess
import sys
from oracle_node_context import evaluate

OUT = Path(__file__).resolve().parent
ROOT = OUT.parent.parent
REPO = Path('/home/user/ddmin-xml-sbfl')
run_id = datetime.now(ZoneInfo('Asia/Colombo')).strftime('%Y%m%d_%H%M%S')
RUN = OUT / 'runs' / run_id
RUN.mkdir(parents=True, exist_ok=False)
seed = '<span>probe</span>'  # Default fragment in the archived probe.
(RUN/'seed.xml').write_text(seed)
summary = {'timestamp': datetime.now(ZoneInfo('Asia/Colombo')).isoformat(),
           'seed': seed, 'seed_characters': len(seed),
           'seed_source': 'default fragment in archived probe.c; no separate historical DDMIN seed was recorded',
           'reducer': 'byte-for-byte scripts/ddmin.py from experiment commit 28b3355',
           'input_model': 'fragment characters only; HTML context fixed; namespace presence varied between runs',
           'oracle': 'fixed accepts + buggy SIGSEGV => FAIL; both accept with equal result/list summaries => PASS; otherwise UNRESOLVED',
           'ddmin': {}, 'checks': {}}

# Verify the historical trigger and the requested modification before reduction.
repeats = [evaluate(seed, mode) for mode in ('original', 'no_namespace') for _ in range(10)]
(RUN/'seed_repeat_checks.json').write_text(json.dumps(repeats, indent=2)+'\n')
assert all(x['classification'] == 'FAIL' for x in repeats if x['mode'] == 'original')
assert all(x['classification'] == 'PASS' for x in repeats if x['mode'] == 'no_namespace')
summary['checks']['seed_repeat_counts'] = {mode: dict(Counter(
    x['classification'] for x in repeats if x['mode'] == mode))
    for mode in ('original', 'no_namespace')}
print('Seed verified: original FAIL 10/10; namespace removed PASS 10/10', flush=True)

for mode in ('original', 'no_namespace'):
    dest = RUN / f'character_ddmin_{mode}'
    env = dict(os.environ, NODE_CONTEXT_MODE=mode, TZ='Asia/Colombo',
               NODE_CONTEXT_ORACLE_LOG=str(RUN/f'oracle_{mode}.jsonl'))
    command = [sys.executable, str(OUT/'ddmin.py'), str(RUN/'seed.xml'),
               '--oracle-module', 'oracle_node_context', '--results-root', str(dest),
               '--temporary-file', str(RUN/f'candidate_{mode}.xml')]
    completed = subprocess.run(command, env=env, capture_output=True, text=True)
    (RUN/f'ddmin_{mode}.stdout.txt').write_text(completed.stdout)
    (RUN/f'ddmin_{mode}.stderr.txt').write_text(completed.stderr)
    dirs = list(dest.iterdir())
    assert len(dirs) == 1
    actual = dirs[0]
    records = [json.loads(line) for line in (actual/'unique_candidates.jsonl').read_text().splitlines()]
    counts = dict(Counter(x['classification'] for x in records))
    info = {'exit_code': completed.returncode, 'counts': counts,
            'unique_candidates': len(records), 'results': str(actual.relative_to(OUT)),
            'command': command}
    if mode == 'original':
        assert completed.returncode == 0, completed.stderr
        info['summary'] = json.loads((actual/'summary.json').read_text())
        original_dir = actual
    else:
        assert completed.returncode == 1 and 'classified as PASS' in completed.stderr
        info['status'] = 'stopped_initial_input_PASS; no minimization performed'
    summary['ddmin'][mode] = info
    print(f'Character DDMIN {mode}: exit={completed.returncode}, {counts}', flush=True)

# Reclassify every candidate actually generated by the original-context DDMIN.
original_records = [json.loads(line) for line in (original_dir/'unique_candidates.jsonl').read_text().splitlines()]
paired = []
for record in original_records:
    fragment = (original_dir/record['saved_path']).read_bytes().decode('utf-8')
    new = evaluate(fragment, 'no_namespace')
    paired.append({'candidate_id': record['candidate_id'], 'fragment': fragment,
                   'original': record['classification'], 'no_namespace': new['classification'],
                   'no_namespace_details': new})
(RUN/'paired_ddmin_candidates.json').write_text(json.dumps(paired, indent=2)+'\n')
with (RUN/'paired_ddmin_candidates.csv').open('w', newline='') as f:
    writer = csv.DictWriter(f, fieldnames=['candidate_id','fragment','original','no_namespace'])
    writer.writeheader()
    writer.writerows({k: r[k] for k in writer.fieldnames} for r in paired)
summary['paired_ddmin_candidates'] = {mode: dict(Counter(x[mode] for x in paired))
                                      for mode in ('original', 'no_namespace')}

# A fresh 24-fragment diagnostic screen. The original report did not preserve
# its complete 24-member corpus; this explicitly does not claim to recreate it.
fragments = ['', ' ', 'x', '&amp;', '<!--x-->', '<?p x?>', '<b/>', '<b>x</b>',
             '<div><em>x</em></div>', '<span>probe</span>', 'hello world', '123',
             '\n', '<a></a>', '<a x="1"/>', '<![CDATA[x]]>', '<a/>text',
             '<a/><b/>', '<b>', '</b>', '<', '&', '&unknown;', '<?xml version="1.0"?>']
assert len(fragments) == len(set(fragments)) == 24
boundary = [evaluate(fragment, mode) for fragment in fragments
             for mode in ('original', 'no_namespace')]
(RUN/'boundary_screen.json').write_text(json.dumps(boundary, indent=2)+'\n')
with (RUN/'boundary_screen.csv').open('w', newline='') as f:
    writer = csv.DictWriter(f, fieldnames=['fragment','mode','classification',
                                         'buggy_returncode','fixed_returncode',
                                         'buggy_parse_result','fixed_parse_result'])
    writer.writeheader()
    for r in boundary:
        writer.writerow({**{k:r[k] for k in ('fragment','mode','classification')},
                         **{f'{v}_{k}':r[v][k] for v in ('buggy','fixed')
                            for k in ('returncode','parse_result')}})
summary['fresh_24_fragment_screen'] = {mode: dict(Counter(
    x['classification'] for x in boundary if x['mode'] == mode))
    for mode in ('original', 'no_namespace')}

# Broader character deletion screening of the same seed is supplementary,
# not DDMIN: test each contiguous substring and each contiguous-block deletion.
deletions = {seed, ''}
for start in range(len(seed)):
    for end in range(start+1, len(seed)+1):
        deletions.add(seed[start:end])
        deletions.add(seed[:start]+seed[end:])
screen = [evaluate(fragment, 'no_namespace')
          for fragment in sorted(deletions, key=lambda s:(len(s),s))]
(RUN/'character_deletion_screen.json').write_text(json.dumps(screen, indent=2)+'\n')
summary['supplementary_character_deletion_screen'] = {
    'kind': 'diagnostic screen, not DDMIN', 'unique_candidates': len(screen),
    'counts': dict(Counter(x['classification'] for x in screen))}
summary['checkout_head_after'] = subprocess.check_output(['git','rev-parse','HEAD'],cwd=REPO,text=True).strip()
summary['checkout_status_after'] = subprocess.check_output(['git','status','--porcelain'],cwd=REPO,text=True)
(RUN/'summary.json').write_text(json.dumps(summary, indent=2)+'\n')
(OUT/'latest_run.txt').write_text(str(RUN.relative_to(OUT))+'\n')
print(json.dumps({k:v for k,v in summary.items() if k in (
    'paired_ddmin_candidates','fresh_24_fragment_screen','supplementary_character_deletion_screen')}, indent=2), flush=True)
print(f'RESULTS: {RUN}', flush=True)
